$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$resources = Join-Path $root 'FlowBlox.UICore/Resources'
function Write-Resources($name, $values, $germanValues) {
    foreach ($language in @('', '.de')) {
        $entries = if ($language) { $germanValues } else { $values }
        $xml = [xml]'<?xml version="1.0" encoding="utf-8"?><root><resheader name="resmimetype"><value>text/microsoft-resx</value></resheader><resheader name="version"><value>2.0</value></resheader><resheader name="reader"><value>System.Resources.ResXResourceReader, System.Windows.Forms</value></resheader><resheader name="writer"><value>System.Resources.ResXResourceWriter, System.Windows.Forms</value></resheader></root>'
        foreach ($key in ($entries.Keys | Sort-Object)) {
            $data = $xml.CreateElement('data'); $data.SetAttribute('name', $key)
            $data.SetAttribute('xml:space', 'preserve')
            $value = $xml.CreateElement('value'); $value.InnerText = $entries[$key]
            [void]$data.AppendChild($value); [void]$xml.DocumentElement.AppendChild($data)
        }
        $xml.Save((Join-Path $resources "$name$language.resx"))
    }
    $properties = ($values.Keys | Sort-Object | ForEach-Object { "    public static string $_ => ResourceManager.GetString(nameof($_), Culture) ?? nameof($_);" }) -join "`n"
    @"
// Generated by scripts/New-DialogResources.ps1.
#nullable enable
using System.Globalization;
using System.Resources;

namespace FlowBlox.UICore.Resources;

public static class $name
{
    public static ResourceManager ResourceManager { get; } = new("FlowBlox.UICore.Resources.$name", typeof($name).Assembly);
    public static CultureInfo? Culture { get; set; }
$properties
}
"@ | Set-Content (Join-Path $resources "$name.Designer.cs") -Encoding UTF8
}
